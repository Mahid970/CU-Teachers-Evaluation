/**
 * The deployed Worker: the Next.js app, plus the daily statistics rebuild.
 *
 * OpenNext's generated worker only answers requests. The cron in wrangler.jsonc
 * fires every night regardless, and with no `scheduled` handler it did nothing:
 * ratings were stored but never reached a teacher's page. This file is what
 * wrangler deploys (see `main`), and it hands requests straight through.
 *
 * The rebuild runs on a schedule rather than on each rating so a teacher cannot
 * watch a number move right after a particular student was in the room.
 *
 * Excluded from tsconfig: it imports the build output, which only exists after
 * `opennextjs-cloudflare build`. Wrangler bundles and type-strips it.
 */
// @ts-ignore: generated by opennextjs-cloudflare build
import handler from "./.open-next/worker.js";
import { rebuildStatsStatements } from "./src/lib/stats-sql";

type Env = { DB: D1Database };

export default {
  fetch: handler.fetch,

  async scheduled(_event: ScheduledController, env: Env, ctx: ExecutionContext) {
    const statements = rebuildStatsStatements(new Date().toISOString().slice(0, 10)).map((sql) => env.DB.prepare(sql));
    // One batch is one transaction: the public numbers are never half rebuilt.
    ctx.waitUntil(env.DB.batch(statements));
  },
};
