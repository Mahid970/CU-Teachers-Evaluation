/**
 * Turns data/cu_teachers.json + the department catalogue into SQL seed
 * statements. Run:  npm run seed:local   /   npm run seed:remote
 *
 * Fails loudly when a department's `unit` no longer matches the scraped data,
 * so a rename upstream can never silently empty a department page.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { DEPARTMENTS, FACULTIES } from "../src/lib/departments";

type ScrapedTeacher = {
  name: string;
  designation: string | null;
  employee_id: string | null;
  photo_url: string | null;
  profile_url: string | null;
};
type ScrapedDept = { department_name: string; teachers: ScrapedTeacher[] };
type Scraped = { faculties: { departments: ScrapedDept[] }[] };

const root = resolve(import.meta.dirname, "..");
const data = JSON.parse(
  readFileSync(resolve(root, "data/cu_teachers.json"), "utf8"),
) as Scraped;

const unitIndex = new Map<string, ScrapedTeacher[]>();
for (const faculty of data.faculties) {
  for (const dept of faculty.departments) {
    unitIndex.set(dept.department_name, dept.teachers);
  }
}

const q = (value: string | null | undefined) =>
  value == null ? "NULL" : `'${value.replace(/'/g, "''")}'`;

const lines: string[] = [
  "-- Generated by scripts/seed.ts — do not edit by hand.",
  "DELETE FROM teachers;",
  "DELETE FROM departments;",
  "DELETE FROM faculties;",
];

FACULTIES.forEach((f, i) => {
  lines.push(
    `INSERT INTO faculties (key, code, name, short_name, sort_order) VALUES (${q(f.key)}, ${q(f.code)}, ${q(f.name)}, ${q(f.shortName)}, ${i});`,
  );
});

const problems: string[] = [];
let teacherCount = 0;
const seenIds = new Set<string>();

DEPARTMENTS.forEach((d, i) => {
  lines.push(
    `INSERT INTO departments (slug, code, name, faculty_key, kind, sort_order) VALUES (${q(d.slug)}, ${q(d.code)}, ${q(d.name)}, ${q(d.faculty)}, ${q(d.kind)}, ${i});`,
  );

  const teachers = unitIndex.get(d.unit);
  if (!teachers) {
    problems.push(`No unit named "${d.unit}" in cu_teachers.json (department ${d.slug})`);
    return;
  }

  teachers.forEach((t, order) => {
    // A handful of teachers are listed under two units (e.g. Management and
    // CUCBA). Keep the first listing so a teacher appears exactly once.
    const id = t.employee_id?.trim();
    if (!id) {
      problems.push(`Teacher "${t.name}" in ${d.slug} has no employee id`);
      return;
    }
    if (seenIds.has(id)) return;
    seenIds.add(id);
    teacherCount += 1;
    lines.push(
      `INSERT INTO teachers (id, name, designation, dept_slug, photo_url, profile_url, active, sort_order) VALUES (${q(id)}, ${q(t.name)}, ${q(t.designation ?? "Teacher")}, ${q(d.slug)}, ${q(t.photo_url)}, ${q(t.profile_url)}, 1, ${order});`,
    );
  });
});

/**
 * Units left out on purpose: no student of theirs can hold a CU student ID in
 * the 8-digit format, so nobody could ever rate them.
 *  - Bureau of Business Research: a research bureau; its one member is already
 *    listed under Accounting.
 *  - Faculty of Medicine units: taught through affiliated medical colleges.
 */
const EXPECTED_UNMAPPED = new Set([
  "Bureau of Business Research",
  "Paediatrics",
  "Community Ophthalmology",
  "Social Science Research",
]);

// Any other unmapped unit is a real problem — that is how a new department
// would show up after a re-scrape.
const mappedUnits = new Set(DEPARTMENTS.map((d) => d.unit));
for (const unit of unitIndex.keys()) {
  if (
    !mappedUnits.has(unit) &&
    !EXPECTED_UNMAPPED.has(unit) &&
    (unitIndex.get(unit)?.length ?? 0) > 0
  ) {
    problems.push(`Unit "${unit}" has teachers but no entry in departments.ts`);
  }
}

const outFile = resolve(root, "migrations/0002_seed.sql");
writeFileSync(outFile, lines.join("\n") + "\n");

console.log(`Wrote ${outFile}`);
console.log(`  faculties:   ${FACULTIES.length}`);
console.log(`  departments: ${DEPARTMENTS.length}`);
console.log(`  teachers:    ${teacherCount}`);
if (problems.length) {
  console.log("\nProblems:");
  for (const p of problems) console.log(`  - ${p}`);
}
